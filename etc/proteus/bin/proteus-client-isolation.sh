#!/bin/bash
# Apply the client network-isolation mode to nftables, and regenerate the
# boot-time seed that decides what applies before this script gets to run.
#
# Two independent settings:
#
#   PROTEUS_CLIENT_ISOLATION = open | isolated      (what we want right now)
#     open      clients may transit through the gateway to other private
#               (RFC1918) LAN hosts -> @client_pivot holds the client VLAN
#     isolated  that transit is dropped; clients reach only the public internet
#               through the VPN tunnels -> @client_pivot is empty
#
#   PROTEUS_CLIENT_ISOLATION_FAILSAFE = open | closed   (what applies if we don't)
#     open      the seed always grants the pivot, so the boot window and any
#               failure of this unit land on the pre-feature permissive
#               behaviour. No lockout risk. This is the default.
#     closed    the seed mirrors the mode, so "isolated" is in force from the
#               first moment of boot and a failure here cannot silently hand
#               clients the LAN.
#
# Note the asymmetry: under failsafe=closed with mode=open the seed still grants
# the pivot. "Failing" to the mode the operator explicitly chose is not a
# security gap, and seeding empty there would blackhole LAN access for a few
# seconds on every boot for no benefit.
set -euo pipefail

log() { printf '[%(%FT%T%z)T] proteus-client-isolation: %s\n' -1 "$*" >&2; }

# Base env then UI overlay (a knob write lands in proteus-local.env). These win
# over anything already in the environment — the config files are the source of
# truth, so `FOO=x proteus-client-isolation.sh` must NOT be able to apply a mode
# the operator never configured. The paths are overridable only so the tests can
# point them at /dev/null and get a hermetic run; nothing in production sets them.
PROTEUS_ENV_FILE="${PROTEUS_ENV_FILE:-/etc/proteus/proteus.env}"
PROTEUS_LOCAL_ENV_FILE="${PROTEUS_LOCAL_ENV_FILE:-/etc/proteus/proteus-local.env}"
# shellcheck disable=SC1090  # runtime-determined path, by design
[ -r "$PROTEUS_ENV_FILE" ]       && . "$PROTEUS_ENV_FILE"
# shellcheck disable=SC1090
[ -r "$PROTEUS_LOCAL_ENV_FILE" ] && . "$PROTEUS_LOCAL_ENV_FILE"

MODE="${PROTEUS_CLIENT_ISOLATION:-open}"
FAILSAFE="${PROTEUS_CLIENT_ISOLATION_FAILSAFE:-open}"
VLAN="${PROTEUS_CLIENT_VLAN_CIDR:-172.16.1.0/24}"
TABLE="inet filter"
SET="client_pivot"
SEED_DIR=/etc/proteus/nft
SEED="$SEED_DIR/client-pivot-seed.nft"

# Fail safe on garbage input: an unrecognised value must never be the reason the
# network silently changes shape. Both default to the permissive setting.
case "$MODE" in
    open|isolated) ;;
    *) log "unknown mode '$MODE' — defaulting to open"; MODE=open ;;
esac
case "$FAILSAFE" in
    open|closed) ;;
    *) log "unknown failsafe '$FAILSAFE' — defaulting to open"; FAILSAFE=open ;;
esac

# Defence in depth: VLAN comes from a root-owned env file, but it is interpolated
# into an nft command AND into a file that /etc/nftables.conf includes at boot.
# Require a bare IPv4 CIDR and nothing else.
if ! [[ "$VLAN" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}/[0-9]{1,2}$ ]]; then
    log "PROTEUS_CLIENT_VLAN_CIDR='$VLAN' is not a plain IPv4 CIDR — refusing to apply"
    exit 1
fi

# ---------------------------------------------------------------------------
# 1. Regenerate the boot seed.
#
# /etc/nftables.conf pulls this file in with a bracket glob, so its ABSENCE is a
# silent no-op (the set stays empty = isolated). Its CORRUPTION is not: a
# half-written line or a CRLF makes the whole ruleset fail to parse, and since
# nftables.conf starts with `flush ruleset` that leaves the box with no firewall
# at all. So: render to a temp file, prove it parses, then rename(2) it into
# place. Never redirect straight onto the live path.
# ---------------------------------------------------------------------------
seed_body() {
    if [ "$FAILSAFE" = open ] || [ "$MODE" = open ]; then
        printf '# proteus: generated by proteus-client-isolation.sh — do not edit\n'
        printf '# failsafe=%s mode=%s -> grant the client LAN pivot at boot\n' "$FAILSAFE" "$MODE"
        printf 'add element %s %s { %s }\n' "$TABLE" "$SET" "$VLAN"
    else
        printf '# proteus: generated by proteus-client-isolation.sh — do not edit\n'
        printf '# failsafe=closed mode=isolated -> client_pivot intentionally empty\n'
    fi
}

# `--print-seed` renders what the next boot would load and exits, without root,
# without touching the ruleset. Answers "what happens if this box reboots right
# now?" — which is otherwise invisible, since the live set and the boot seed are
# allowed to differ (failsafe=open + mode=isolated is the default shape).
if [ "${1:-}" = "--print-seed" ]; then
    seed_body
    exit 0
fi

write_seed() {
    mkdir -p "$SEED_DIR"
    # Root-only. Everything nftables.conf includes at boot is firewall content;
    # the unprivileged web-UI user must never be able to write here.
    chown root:root "$SEED_DIR" 2>/dev/null || true
    chmod 0755 "$SEED_DIR"

    local tmp="$SEED_DIR/.client-pivot-seed.nft.tmp"
    local scratch; scratch=$(mktemp -d)
    # shellcheck disable=SC2064  # expand now: we want this exact path removed
    trap "rm -rf '$scratch'" RETURN

    seed_body > "$tmp"
    chmod 0644 "$tmp"

    if grep -q $'\r' "$tmp"; then
        log "generated seed contains CR — refusing to publish (would break the boot ruleset)"
        rm -f "$tmp"; return 1
    fi

    # Parse-check the seed exactly as the boot loader will see it: a table
    # declaring the set, then the seed included at top level. `nft -c` resolves
    # the set reference and type-checks the element without committing anything.
    cat > "$scratch/check.nft" <<EOF
table inet filter {
    set $SET {
        type ipv4_addr
        flags interval
    }
}
include "$tmp"
EOF
    if ! nft -c -f "$scratch/check.nft" 2>"$scratch/err"; then
        log "generated seed failed nft -c — NOT publishing: $(tr '\n' ' ' <"$scratch/err")"
        rm -f "$tmp"; return 1
    fi

    sync -d "$tmp" 2>/dev/null || sync
    mv -f "$tmp" "$SEED"
    sync -d "$SEED_DIR" 2>/dev/null || sync
}

if [ "$(id -u)" -ne 0 ]; then
    log "must run as root (writes $SEED and the live ruleset)"
    exit 1
fi

if write_seed; then
    log "boot seed updated (failsafe=$FAILSAFE mode=$MODE) -> $SEED"
else
    # A stale-but-valid seed is far better than no seed or a broken one, so keep
    # whatever is already on disk and carry on to the live apply, which is what
    # actually governs the running system.
    log "boot seed NOT updated — keeping previous $SEED (live ruleset still applied below)"
fi

# ---------------------------------------------------------------------------
# 2. Apply the mode to the running ruleset.
#
# The set lives in nftables.conf. If the ruleset isn't loaded yet (this ran
# before nftables.service, or an older ruleset predating the gate), there is
# nothing to toggle — don't wedge boot; the seed above already governs it.
# ---------------------------------------------------------------------------
if ! nft list set $TABLE "$SET" >/dev/null 2>&1; then
    log "set $TABLE $SET not present (nftables not loaded?) — seed written, nothing live to apply"
    exit 0
fi

if [ "$MODE" = isolated ]; then
    nft flush set $TABLE "$SET"
    log "mode=isolated — client LAN pivot BLOCKED (public egress via VPN only)"
else
    # Atomic flush+add so the pivot is never momentarily dropped while re-opening.
    nft -f - <<EOF
flush set $TABLE $SET
add element $TABLE $SET { $VLAN }
EOF
    log "mode=open — client LAN pivot ALLOWED (VLAN $VLAN)"
fi
